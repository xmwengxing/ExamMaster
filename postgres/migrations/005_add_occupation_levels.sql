-- 为 occupation_list 表添加职业等级字段
-- 用于限制该职业可申报的等级范围
-- 创建时间: 2026-03-06

-- ============================================================
-- 添加职业等级字段
-- ============================================================

-- 添加职业等级字段（存储为数组，如：['五级', '四级', '三级']）
ALTER TABLE occupation_list 
ADD COLUMN IF NOT EXISTS levels TEXT[] DEFAULT ARRAY['五级', '四级', '三级', '二级', '一级'];

-- ============================================================
-- 注释说明
-- ============================================================

COMMENT ON COLUMN occupation_list.levels IS '职业等级范围 - 该职业可申报的等级列表，如：[五级, 四级, 三级]';

-- ============================================================
-- 更新现有数据
-- ============================================================

-- 为现有记录设置默认等级（全部等级）
UPDATE occupation_list 
SET levels = ARRAY['五级', '四级', '三级', '二级', '一级']
WHERE levels IS NULL;

